package.path='modkit/SceneZOI_93C44199/workspace/lua/B1/?.lua;'..package.path
local L=require('SceneZOI.SofaLayout');local P=require('SceneZOI.FurniturePairs');local V=require('SceneZOI.DataValidation')
local function slot(name,x,y,yaw,tags)
 return{component_name=name,slot_name='slot_'..name,position={x=x,y=y or 70,z=0},yaw_degrees=yaw or 0,tags=tags or{'Sit'}}
end
local function layout(rows,model)return L.build(model or 'TotallyNewModSofa','123',rows)end
local p=assert(layout({slot('AnyNameA',45),slot('AnyNameB',-45)}))
assert(p.objects[1]=='TotallyNewModSofa'and #p.sitting_spots==2 and #p.seat_pairs==1)
assert(p.surface_height_cm==44 and p.sitting_spots[1].offset_cm.y==17)
local q=assert(layout({slot('AnyNameB',-45),slot('AnyNameA',45)}))
assert(V.equal(p,q),'Native enumeration order must not change spot or pair IDs')
q=assert(layout({slot('A',45),slot('A_alt',45,80,0,{'Sit_PassOut'}),slot('B',-45),slot('B_alt',-45,70,0,{'Sit_PassOut'})}))
assert(#q.sitting_spots==2 and #q.seat_pairs==1)
assert(#q.sitting_spots[1].slots==2 and #q.sitting_spots[2].slots==2,'Pass-out aliases are not separate seats')
q=assert(layout({slot('A',90),slot('B',0),slot('C',-90)}))
assert(#q.seat_pairs==2 and P.overlap(q.seat_pairs[1].spots,q.seat_pairs[2].spots),'Three seats have two overlapping adjacent pairs')
q=assert(layout({slot('A',82,-44),slot('B',-19,-44),slot('C',-39,-19,-90),slot('D',-39,90,-90)}))
assert(#q.sitting_spots==4 and #q.seat_pairs==2 and not P.overlap(q.seat_pairs[1].spots,q.seat_pairs[2].spots),'Corner has two disjoint straight runs')
q=assert(layout({slot('A',82,-44),slot('B',-19,-44),slot('C',-39,90,-90)}))
assert(#q.sitting_spots==3 and #q.seat_pairs==1,'Do not create diagonal pairs across a corner')
assert(not layout({slot('A',0),slot('B',0)}),'Coincident normal aliases are one physical spot')
assert(not layout({slot('A',0),slot('B',200)}),'Do not bridge an unsupported gap')
assert(not layout({slot('A',0),slot('B',90,72)}),'Do not pair different seat rows')
assert(not layout({slot('A',0),slot('B',90,70,15)}),'Do not pair seats facing different ways')
assert(not layout({slot('A',0,70,0,{'Sit_PassOut'}),slot('B',90,70,0,{'Sit_PassOut'})}),'Alternate postures alone do not prove normal seating')
assert(not pcall(layout,{slot('A',0),slot('A',90)}),'Duplicate native keys must fail')
assert(not pcall(layout,{slot('A',0),slot('B',90),slot('orphan',160,70,0,{'Sit_PassOut'})}),'Unmapped sitting aliases must fail')
local bad={slot('A',0),slot('B',90)};bad[1].position.x=0/0;assert(not pcall(layout,bad))
bad={slot('A',0),slot('B',90)};bad[1].position.z=2;assert(not layout(bad),'Do not pair different support planes')
print('Automatic sofa topology passed: arbitrary model/slot names, alias grouping, deterministic IDs, adjacent pairs, corner runs and graceful unsupported layouts.')
